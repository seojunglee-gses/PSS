export function translate(locale: Locale, key: string, values: Record<string, string | number> = {}) {
  const text = messagesByLocale[locale][key] ?? messagesByLocale.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => values[name] === undefined ? match : String(values[name]));
}

// Translate built-in messages, including saved legacy notices, without changing stored data.
const messageKeys = new Map<string, string>();
const messagePatterns: { key: string; names: string[]; pattern: RegExp }[] = [];
for (const catalog of Object.values(messagesByLocale)) for (const [key, text] of Object.entries(catalog)) {
  if (!text.includes("{")) messageKeys.set(text, key);
  else {
    const names: string[] = [];
    const escaped = text.replace(/[.*+?^$()|[\]\\]/g, "\\$&");
    const pattern = escaped.replace(/\{(\w+)\}/g, (_, name) => { names.push(name); return "(.+?)"; });
    messagePatterns.push({ key, names, pattern: new RegExp("^" + pattern + "$", "s") });
  }
}
// Only built-in starter content is translated; authored project/case prose is retained.
export function localizeDefaultContent(locale: Locale, content: string) {
  const entry = Object.entries(messagesByLocale.en).find(([key, text]) => key.startsWith("default.") && text === content);
  return entry ? translate(locale, entry[0]) : content;
}
export function localizeMessage(locale: Locale, message: string, fallbackKey?: string) {
  if (Object.prototype.hasOwnProperty.call(messagesByLocale.en, message)) return translate(locale, message);
  const key = messageKeys.get(message);
  if (key) return translate(locale, key);
  for (const item of messagePatterns) {
    const match = item.pattern.exec(message);
    if (match) return translate(locale, item.key, Object.fromEntries(item.names.map((name, i) => [name, match[i + 1]])));
  }
  return fallbackKey ? translate(locale, fallbackKey) : message;
}

type I18nContextValue = {
  locale: Locale;
  setLocale: (nextLocale: Locale) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
  localize: (message: string, fallbackKey?: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("en");

  useEffect(() => {
    if (typeof window === "undefined") {
      return;
    }

    const storedLocale = window.localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (storedLocale && messagesByLocale[storedLocale]) {
      setLocale(storedLocale);
    }
  }, []);

  useEffect(() => { document.documentElement.lang = locale; }, [locale]);

  const updateLocale = (nextLocale: Locale) => {
    setLocale(nextLocale);
    if (typeof window !== "undefined") {
      window.localStorage.setItem(STORAGE_KEY, nextLocale);
    }
  };

  const value = useMemo<I18nContextValue>(() => {
    return {
      locale,
      setLocale: updateLocale,
      t: (key, values) => translate(locale, key, values),
      localize: (message, fallbackKey) => localizeMessage(locale, message, fallbackKey),
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return context;
}
